export function drawChessPiece(g, code) {
  const white = code === code.toUpperCase();
  const base = white ? 0xf2eadb : 0x34302d, edge = white ? 0x4a3a2a : 0x0d0b0a;
  const sh = SHAPES[code.toLowerCase()];
  g.fillStyle(0x000000, 0.28);
  g.fillEllipse(0, 25, 38, 9);
  for (const p of sh.polys) shaded(g, p.map(m), base, edge);
  for (const [cx, cy, r] of sh.circles || []) {
    const c = m([cx, cy]);
    shadedCircle(g, c[0], c[1], r * K, base, edge);
  }
  g.lineStyle(1.3, edge, 0.9);
  for (const [x1, y1, x2, y2] of sh.lines || []) {
    const a = m([x1, y1]), b = m([x2, y2]);
    g.beginPath();
    g.moveTo(a[0], a[1]);
    g.lineTo(b[0], b[1]);
    g.strokePath();
  }
}
